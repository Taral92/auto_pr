def _entry(name: str) -> tuple[int, str, int]:
    try:
        return _TABLE[name]
    except KeyError as e:
        raise LookupError(f"unknown symbol {name!r} at table v{TABLE_VERSION}") from e


def encode_one(name: str, value: bytes) -> bytes:
    code, _label, width = _entry(name)
    return bytes([code]) + value[:width].ljust(width, b"\x00")


def encode_batch(names: list[str], values: list[bytes]) -> bytes:
    """Encode a whole batch in one pass.

    Batching replaced per-record encoding when the store moved to put_many.
    The buffer is local to the call, so two threads encoding at once do not
    share it; the table itself is read only after import.
    """
    if len(names) != len(values):
        raise ValueError("names and values must be the same length")
    buffer = bytearray()
    for name, value in zip(names, values):
        buffer += encode_one(name, value)
    return bytes(buffer)
